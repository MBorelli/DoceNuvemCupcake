"""Testes do adaptador PostgreSQL usando uma conexão falsa (não precisa de
servidor Postgres): conferem a tradução do SQL escrito no estilo sqlite3."""
import unittest

from app.database import SCHEMA, ConexaoPostgres


class CursorFalso:
    def __init__(self, rowcount=1, linha=None):
        self.rowcount = rowcount
        self._linha = linha

    def fetchone(self):
        return self._linha

    def executemany(self, sql, dados):
        self.executado = (sql, dados)

    def __enter__(self):
        return self

    def __exit__(self, *args):
        pass


class ConexaoFalsa:
    def __init__(self):
        self.comandos = []
        self.cursor_falso = CursorFalso()

    def execute(self, sql, params=None):
        self.comandos.append((sql, params))
        return CursorFalso(linha={"id": 42} if "RETURNING id" in sql else None)

    def cursor(self):
        return self.cursor_falso


def adaptador():
    conexao = ConexaoPostgres.__new__(ConexaoPostgres)  # pula a conexão real
    conexao._con = ConexaoFalsa()
    return conexao


class TestAdaptadorPostgres(unittest.TestCase):
    def test_placeholders(self):
        db = adaptador()
        db.execute("SELECT * FROM produtos WHERE id = ? AND categoria = ?", (1, "Frutas"))
        sql, params = db._con.comandos[-1]
        self.assertEqual(sql, "SELECT * FROM produtos WHERE id = %s AND categoria = %s")
        self.assertEqual(params, (1, "Frutas"))

    def test_insert_devolve_lastrowid(self):
        db = adaptador()
        cur = db.execute("INSERT INTO clientes (nome) VALUES (?)", ("Ana",))
        self.assertTrue(db._con.comandos[-1][0].endswith("RETURNING id"))
        self.assertEqual(cur.lastrowid, 42)

    def test_update_nao_recebe_returning(self):
        db = adaptador()
        cur = db.execute("UPDATE produtos SET estoque = estoque - ? WHERE id = ?", (1, 2))
        self.assertNotIn("RETURNING", db._con.comandos[-1][0])
        self.assertEqual(cur.rowcount, 1)

    def test_porcentagem_literal_e_escapada(self):
        db = adaptador()
        db.execute("SELECT '100%' AS x WHERE 1 = ?", (1,))
        self.assertEqual(db._con.comandos[-1][0], "SELECT '100%%' AS x WHERE 1 = %s")

    def test_sem_parametros_nao_altera_sql(self):
        db = adaptador()
        db.execute("SELECT COUNT(*) AS total FROM produtos")
        self.assertEqual(db._con.comandos[-1], ("SELECT COUNT(*) AS total FROM produtos", None))

    def test_schema_convertido(self):
        db = adaptador()
        db.executescript(SCHEMA)
        comandos = [c for c, _ in db._con.comandos]
        self.assertEqual(sum(c.strip().startswith("CREATE TABLE") for c in comandos), 7)
        self.assertFalse(any("AUTOINCREMENT" in c for c in comandos))
        self.assertTrue(all("GENERATED BY DEFAULT AS IDENTITY" in c
                            for c in comandos if c.strip().startswith("CREATE TABLE")))

    def test_executemany(self):
        db = adaptador()
        db.executemany("INSERT INTO produtos (nome) VALUES (?)", [("A",), ("B",)])
        sql, dados = db._con.cursor_falso.executado
        self.assertEqual(sql, "INSERT INTO produtos (nome) VALUES (%s)")
        self.assertEqual(dados, [("A",), ("B",)])


if __name__ == "__main__":
    unittest.main()
